#[cfg(test)]
mod more_tests {
    use super::*;

    fn eval(script: &str) -> LuaResult<()> {
        let lua = Lua::new();
        register(&lua)?;
        register_host(&lua)?;
        lua.load(script).exec()
    }

    #[test]
    fn empty_password_raises() {
        let err = eval(r#"ansible.vault.encrypt("x", "")"#).unwrap_err();
        assert!(err.to_string().contains("empty password"), "{err}");
        let err = eval(r#"ansible.vault.decrypt("$ANSIBLE_VAULT;1.1;AES256\n00", "")"#).unwrap_err();
        assert!(err.to_string().contains("empty password"), "{err}");
    }

    #[test]
    fn encrypt_is_host_only() {
        let lua = Lua::new();
        register(&lua).unwrap();
        lua.load("assert(ansible.vault.encrypt == nil and ansible.vault.decrypt ~= nil)")
            .exec()
            .unwrap();
    }

    #[test]
    fn is_vault_sniffs_the_header() {
        eval(
            r#"
            assert(ansible.vault.is_vault("$ANSIBLE_VAULT;1.1;AES256\nabc"))
            assert(ansible.vault.is_vault("$ANSIBLE_VAULT;1.2;AES256;prod\nabc"))
            assert(not ansible.vault.is_vault("$ANSIBLE_VAULT;1.2;AES256\nabc"))
            assert(not ansible.vault.is_vault("hello"))
        "#,
        )
        .unwrap();
    }

    #[test]
    fn reads_a_1_2_header_and_indented_body() {
        eval(
            r#"
            local v = ansible.vault.encrypt("secret", "pw")
            local lines = {}
            for l in v:gmatch("[^\n]+") do table.insert(lines, l) end
            lines[1] = "$ANSIBLE_VAULT;1.2;AES256;label"
            for i = 2, #lines do lines[i] = "    " .. lines[i] end
            assert(ansible.vault.decrypt(table.concat(lines, "\n") .. "\n\n", "pw") == "secret")
        "#,
        )
        .unwrap();
    }

    #[test]
    fn tampered_ciphertext_and_malformed_payload_raise() {
        let err = eval(
            r#"
            local v = ansible.vault.encrypt("secret", "pw")
            -- flip the last hex digit of the body
            local last = v:sub(-2, -2)
            v = v:sub(1, -3) .. (last == "0" and "1" or "0") .. "\n"
            ansible.vault.decrypt(v, "pw")
        "#,
        )
        .unwrap_err();
        let msg = err.to_string();
        assert!(msg.contains("HMAC") || msg.contains("malformed"), "{msg}");
        let err = eval(r#"ansible.vault.decrypt("$ANSIBLE_VAULT;1.1;AES256\nzz", "pw")"#).unwrap_err();
        assert!(err.to_string().contains("malformed"), "{err}");
        let err = eval(r#"ansible.vault.decrypt("", "pw")"#).unwrap_err();
        assert!(err.to_string().contains("empty input"), "{err}");
    }
}
